/**
 * task-025b O2 — `chunkAppearsIn` 의 동사 활용형 경로(`曲がります` ↔ `曲がってください`).
 * 서버 `learning/lessons/matching.ts` 는 학습자 자유 발화 판정용이라 의미가 달라 이 경로를 공유하지 않는다
 * (golden 동치 대상은 `lessonMatching.test.ts` 의 정규화 두 정규식뿐). 최우선은 오탐 0 이라, 허용 케이스는 적게·
 * 오탐 방어 케이스는 많이 둔다 — 방어 케이스가 하나라도 true 가 되면 ④ 가 "엉뚱한 모범 답"을 통과시킨다는 뜻이다.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { chunkAppearsIn } from '../structuredResponse/matching'

/** reading 은 히라가나 읽기 — 활용형 경로는 textJa 기준이므로 reading 이 모범 답에 없는 상황을 일부러 만든다. */
function chunk(textJa: string, reading: string) {
  return { textJa, reading }
}

// ── 허용(같은 동사의 활용형) ────────────────────────────────────────────

test('활용형 허용: 5단 `曲がります` ↔ `曲がってください`(O2 원 사례)', () => {
  const c = chunk('曲がります', 'まがります')
  assert.equal(chunkAppearsIn('次の角を右に曲がってください。', c), true)
  assert.equal(chunkAppearsIn('昨日、右に曲がりました。', c), true)
})

test('활용형 허용: 1단 `食べます` ↔ `食べてください`·`食べました`·사전형 `食べる`', () => {
  const c = chunk('食べます', 'たべます')
  assert.equal(chunkAppearsIn('ここで食べてください。', c), true)
  assert.equal(chunkAppearsIn('もう食べました。', c), true)
  assert.equal(chunkAppearsIn('朝は何も食べると眠くなります。', c), true)
})

test('활용형 허용: する 동사 `お願いします` ↔ `お願いしてください`, 5단 `手伝います` ↔ `手伝ってください`', () => {
  assert.equal(chunkAppearsIn('先生にお願いしてください。', chunk('お願いします', 'おねがいします')), true)
  assert.equal(chunkAppearsIn('友達を手伝ってください。', chunk('手伝います', 'てつだいます')), true)
})

test('활용형 허용: 사전형 목표 `考える` ↔ `考えて`, `使う` 는 어간이 1글자라 제외(아래 방어 케이스)', () => {
  assert.equal(chunkAppearsIn('よく考えて決めてください。', chunk('考える', 'かんがえる')), true)
})

// ── 오탐 방어(전부 false 여야 한다) ─────────────────────────────────────

test('오탐 방어: 어간이 같은 다른 단어(`食べます` ↛ `食べ物`, `曲がります` ↛ `曲がり角`) — 어간 부분 문자열만으로는 안 통과한다', () => {
  assert.equal(chunkAppearsIn('この食べ物はおいしいです。', chunk('食べます', 'たべます')), false)
  assert.equal(chunkAppearsIn('次の曲がり角で止まってください。', chunk('曲がります', 'まがります')), false)
})

test('오탐 방어: 어간 1글자 동사(`飲みます`·`行きます`·`使います`)는 활용형 경로를 아예 쓰지 않는다 — 같은 한 글자를 공유하는 다른 동사와 겹친다', () => {
  assert.equal(chunkAppearsIn('水を飲んでください。', chunk('飲みます', 'のみます')), false)
  assert.equal(chunkAppearsIn('学校へ行ってください。', chunk('行きます', 'いきます')), false)
  assert.equal(chunkAppearsIn('ペンを使ってください。', chunk('使います', 'つかいます')), false)
})

test('오탐 방어: 가나뿐인 조각(`あります`·`います`·`する`)은 한자가 없어 어간 가드에서 걸러진다', () => {
  assert.equal(chunkAppearsIn('ここにあってください。', chunk('あります', 'あります')), false)
  assert.equal(chunkAppearsIn('そこにいてください。', chunk('います', 'います')), false)
  assert.equal(chunkAppearsIn('静かにしてください。', chunk('する', 'する')), false)
})

test('오탐 방어: 부정형 목표(`分かりません`·`食べませんでした`)는 활용형 후보를 만들지 않는다(뜻이 반대인 긍정문에 걸리면 안 된다)', () => {
  assert.equal(chunkAppearsIn('よく分かってください。', chunk('分かりません', 'わかりません')), false)
  assert.equal(chunkAppearsIn('朝は食べてください。', chunk('食べませんでした', 'たべませんでした')), false)
})

test('오탐 방어: 활용 뒤에 부정이 이어지면 세지 않는다(`食べていません`·`食べたくない`·`食べたことがない`)', () => {
  const c = chunk('食べます', 'たべます')
  assert.equal(chunkAppearsIn('まだ食べていません。', c), false)
  assert.equal(chunkAppearsIn('今は食べたくないです。', c), false)
  assert.equal(chunkAppearsIn('寿司は食べたことがないです。', c), false)
  // 같은 문장에 긍정 출현이 따로 있으면 그 출현으로 통과한다.
  assert.equal(chunkAppearsIn('まだ食べていませんが、あとで食べてください。', c), true)
})

test('오탐 방어: 繋辞 `お疲れ様です` 는 `お疲れ様でした` 로 인정하지 않는다(동사가 아니다)', () => {
  assert.equal(chunkAppearsIn('今日もお疲れ様でした。', chunk('お疲れ様です', 'おつかれさまです')), false)
})

test('오탐 방어: 전혀 다른 문장·다른 동사는 통과하지 않는다', () => {
  assert.equal(chunkAppearsIn('駅まで歩いてください。', chunk('曲がります', 'まがります')), false)
  assert.equal(chunkAppearsIn('先生に聞いてください。', chunk('手伝います', 'てつだいます')), false)
  assert.equal(chunkAppearsIn('', chunk('食べます', 'たべます')), false)
})

test('오탐 방어: 어간이 길어도 꼬리가 완전하지 않으면 안 된다(`考える` ↛ `考え方`)', () => {
  assert.equal(chunkAppearsIn('その考え方は面白いです。', chunk('考える', 'かんがえる')), false)
})

